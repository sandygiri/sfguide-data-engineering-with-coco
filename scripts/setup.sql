SET MY_USER = CURRENT_USER();

-- Roles (SECURITYADMIN or USERADMIN has privileges to create roles and grant role assignments)
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS DEMO_ROLE;
GRANT ROLE DEMO_ROLE TO ROLE SYSADMIN;
GRANT ROLE DEMO_ROLE TO USER IDENTIFIER($MY_USER);

-- Warehouses, Databases, and Schemas (SYSADMIN has privileges to create warehouses and databases)
USE ROLE SYSADMIN;

-- Warehouses
CREATE WAREHOUSE IF NOT EXISTS DEMO_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 300 AUTO_RESUME = TRUE;
GRANT OWNERSHIP ON WAREHOUSE DEMO_WH TO ROLE DEMO_ROLE REVOKE CURRENT GRANTS;

-- Databases
CREATE DATABASE IF NOT EXISTS DEMO_DB;
GRANT OWNERSHIP ON DATABASE DEMO_DB TO ROLE DEMO_ROLE REVOKE CURRENT GRANTS;

-- Schema
CREATE SCHEMA IF NOT EXISTS DEMO_DB.TPCH_TRANSFORMED;
GRANT OWNERSHIP ON SCHEMA DEMO_DB.TPCH_TRANSFORMED TO ROLE DEMO_ROLE REVOKE CURRENT GRANTS;